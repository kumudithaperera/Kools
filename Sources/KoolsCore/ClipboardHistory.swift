import Foundation

/// One thing that was copied.
public struct ClipboardEntry: Identifiable, Equatable, Sendable {
    public let id: UUID
    public let text: String
    public internal(set) var copiedAt: Date

    init(id: UUID, text: String, copiedAt: Date) {
        self.id = id
        self.text = text
        self.copiedAt = copiedAt
    }

    /// The text on one line, shortened for a list row.
    public var preview: String { Self.preview(of: text) }

    public static func preview(of text: String, limit: Int = 140) -> String {
        let collapsed = text.split(whereSeparator: \.isNewline)
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }
            .joined(separator: " ")
        return collapsed.count > limit ? String(collapsed.prefix(limit)) + "…" : collapsed
    }
}

/// Text recently copied, newest first. It lives in memory only: each entry
/// is dropped 12 hours after it was copied, and the list and the size of an
/// entry are capped so it can never grow without bound.
public struct ClipboardHistory: Equatable, Sendable {
    public static let lifetime: TimeInterval = 12 * 60 * 60
    public static let maxEntries = 50
    /// Larger copies (a whole file pasted as text, say) are not kept.
    public static let maxBytes = 100_000

    /// Pasteboard types apps use to mark a copy as secret or machine-made
    /// (see nspasteboard.org). Password managers set the first one.
    public static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    public private(set) var entries: [ClipboardEntry] = []

    public init() {}

    public var isEmpty: Bool { entries.isEmpty }

    /// Whether a pasteboard with these types should be recorded: not marked
    /// private, and not a copy of files (Finder also puts their names there as text).
    public static func isRecordable(types: [String], hasFiles: Bool) -> Bool {
        !hasFiles && privateTypes.isDisjoint(with: types)
    }

    /// Records a copy. Copying the same text again moves it back to the top
    /// and restarts its 12 hours. Returns false when the text is ignored:
    /// blank, or over `maxBytes`.
    @discardableResult
    public mutating func add(_ text: String, at date: Date = .now) -> Bool {
        guard text.utf8.count <= Self.maxBytes,
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        else { return false }
        if let index = entries.firstIndex(where: { $0.text == text }) {
            var entry = entries.remove(at: index)
            entry.copiedAt = date
            entries.insert(entry, at: 0)
        } else {
            entries.insert(ClipboardEntry(id: UUID(), text: text, copiedAt: date), at: 0)
            if entries.count > Self.maxEntries {
                entries.removeLast(entries.count - Self.maxEntries)
            }
        }
        return true
    }

    public func hasExpired(now: Date = .now) -> Bool {
        entries.contains { Self.isExpired($0, now: now) }
    }

    /// Drops entries copied 12 hours ago or earlier. Returns whether any went.
    @discardableResult
    public mutating func prune(now: Date = .now) -> Bool {
        let before = entries.count
        entries.removeAll { Self.isExpired($0, now: now) }
        return entries.count != before
    }

    public mutating func remove(_ id: UUID) {
        entries.removeAll { $0.id == id }
    }

    public mutating func removeAll() {
        entries.removeAll()
    }

    private static func isExpired(_ entry: ClipboardEntry, now: Date) -> Bool {
        now.timeIntervalSince(entry.copiedAt) >= lifetime
    }
}
